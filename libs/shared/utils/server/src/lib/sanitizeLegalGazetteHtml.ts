import render from 'dom-serializer'
import { findAll, findOne } from 'domutils'
import { parseDocument } from 'htmlparser2'
import sanitizeHtml from 'sanitize-html'

const ALIGNMENTS = /^(left|right|center|justify)$/i
const TEXT_ALIGN = { 'text-align': [ALIGNMENTS] }
const CELL_STYLES = {
  ...TEXT_ALIGN,
  'vertical-align': [/^(top|middle|bottom)$/i],
}

const ALIGNABLE_BLOCKS = ['p', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6']
const CELLS = ['td', 'th']

const BLOCK_TAGS = new Set([
  ...ALIGNABLE_BLOCKS,
  ...CELLS,
  'div',
  'blockquote',
  'pre',
  'hr',
  'ul',
  'ol',
  'li',
  'table',
  'thead',
  'tbody',
  'tfoot',
  'tr',
])

/**
 * Word and Google Docs wrap text in `<div>`, which the editor cannot hold.
 * A div that holds only inline content stands for a paragraph and becomes
 * one; unwrapping it instead would run its text into the next block. A div
 * that wraps other blocks (Word's `WordSection1`) is just a container and is
 * unwrapped, since a `<p>` cannot contain blocks.
 */
const divsToParagraphs = (html: string): string => {
  // Entities stay encoded through this pass, so typed text such as "&lt;b&gt;"
  // is not turned into markup before the sanitizer sees it.
  const doc = parseDocument(html, { decodeEntities: false })
  const divs = findAll(
    (node) => node.name.toLowerCase() === 'div',
    doc.children,
  )
  for (const div of divs) {
    const wrapsBlocks = !!findOne(
      (node) => BLOCK_TAGS.has(node.name.toLowerCase()),
      div.children,
    )
    if (!wrapsBlocks) div.name = 'p'
  }
  return render(doc, { decodeEntities: false })
}

/**
 * Moves a legacy `align` attribute into `text-align`, which is the only form
 * the editor writes. Without this an old `<p align="center">` would lose its
 * alignment, because `align` is not an allowed attribute.
 */
const alignToStyle: sanitizeHtml.Transformer = (tagName, attribs) => {
  const { align, ...rest } = attribs
  const value = align?.trim().toLowerCase()
  if (
    !value ||
    !ALIGNMENTS.test(value) ||
    /text-align/i.test(rest.style ?? '')
  ) {
    return { tagName, attribs: rest }
  }
  const style = rest.style?.trim().replace(/;?$/, '; ') ?? ''
  return {
    tagName,
    attribs: { ...rest, style: `${style}text-align: ${value}` },
  }
}

/**
 * What a Legal Gazette advert body may contain once it is stored: what the
 * editor can produce, and nothing that could run in a reader's browser.
 *
 * Advert HTML is rendered through dangerouslySetInnerHTML in the admin, on the
 * public web and into the PDF. The allow-list mirrors what EditorV2
 * (`@dmr.is/regulations-tools`) holds without loss: text pasted from Word or
 * Google Docs arrives full of `<span style>`, colours and fonts that the
 * editor warns about and drops on the next save anyway.
 *
 * Deliberately narrower than the editor:
 * - no `<img>`: Legal Gazette has no upload, so an image can only be a
 *   remote URL or a data URI that came in with a paste
 * - no `id`, `class` or `data-autogenerated`: those are regulation markup
 * - inline styles are limited to alignment, the only styling the Legal
 *   Gazette toolbar offers
 *
 * Disallowed tags are unwrapped and their text kept, except the ones whose
 * content is never reader text, which are dropped with their content.
 */
const OPTIONS: sanitizeHtml.IOptions = {
  allowedTags: [
    ...ALIGNABLE_BLOCKS,
    'br',
    'blockquote',
    'hr',
    'strong',
    'b',
    'em',
    'i',
    'u',
    's',
    'sub',
    'sup',
    'ol',
    'ul',
    'li',
    'a',
    'table',
    'thead',
    'tbody',
    'tfoot',
    'tr',
    ...CELLS,
  ],
  disallowedTagsMode: 'discard',
  nonTextTags: ['script', 'style', 'textarea', 'option', 'title', 'noscript'],
  allowedAttributes: {
    ...Object.fromEntries(ALIGNABLE_BLOCKS.map((tag) => [tag, ['style']])),
    ...Object.fromEntries(
      CELLS.map((tag) => [tag, ['style', 'colspan', 'rowspan']]),
    ),
    ol: ['start', 'type'],
    a: ['href', 'target', 'rel'],
  },
  allowedStyles: {
    ...Object.fromEntries(ALIGNABLE_BLOCKS.map((tag) => [tag, TEXT_ALIGN])),
    ...Object.fromEntries(CELLS.map((tag) => [tag, CELL_STYLES])),
  },
  allowedSchemes: ['http', 'https', 'mailto', 'tel'],
  allowedSchemesAppliedToAttributes: ['href'],
  allowProtocolRelative: false,
  transformTags: {
    ...Object.fromEntries(
      [...ALIGNABLE_BLOCKS, ...CELLS].map((tag) => [tag, alignToStyle]),
    ),
    a: (tagName, attribs) => {
      if (attribs.target !== '_blank') {
        const { target: _target, rel: _rel, ...rest } = attribs
        return { tagName, attribs: rest }
      }
      return { tagName, attribs: { ...attribs, rel: 'noopener noreferrer' } }
    },
  },
}

/**
 * Cleans a Legal Gazette advert body before it is stored. Null and undefined
 * pass through unchanged, so an update that leaves the body out does not
 * clear it.
 */
export function sanitizeLegalGazetteHtml<T extends string | null | undefined>(
  html: T,
): T {
  if (typeof html !== 'string' || html === '') return html
  return sanitizeHtml(divsToParagraphs(html), OPTIONS) as T
}
